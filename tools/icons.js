#!/usr/bin/env node
// BANZAI 1.3.2: Darren's 13 original class identities -> transparent RGBA masters.
//   node tools/icons.js          check the sources and the class mapping, extract every class at
//                                full resolution, write assets/identity/class-<class>.png and
//                                assets/identity/class-provenance.json, and the QA sheets
//                                (build/icons - git-ignored, never built into the addon)
//   node tools/icons.js --check  derive every master again and compare it with the files and
//                                the provenance (nothing is written; the validator runs this)
// The JPEGs in design-references are only read. The build (tools/build.js) never reads them: it
// converts the masters (tools/lib/identity.js). See docs/BANZAI-IDENTITY-ICONS.md.
'use strict';

const fs = require('fs');
const path = require('path');
const art = require('./lib/classart');
const png = require('./lib/png');
const qa = require('./lib/iconqa');
const identity = require('./lib/identity');
const resample = require('./lib/resample');

const ROOT = path.join(__dirname, '..');
const ASSETS = path.join(ROOT, 'assets', 'identity');
const QA = path.join(ROOT, 'build', 'icons');

function derive() {
  const mapping = art.loadMapping(ROOT);
  const sources = art.verifySources(ROOT, mapping);
  if (sources.errors.length) throw new Error('class sources:\n  ' + sources.errors.join('\n  '));
  const results = {};
  for (const cls of art.CLASSES) {
    const entry = mapping.classes[cls];
    results[cls] = art.extract(fs.readFileSync(path.join(sources.dir, entry.source)));
  }
  const Rt = art.targetRadius(art.CLASSES.map((c) => results[c].fit));
  for (const cls of art.CLASSES) {
    const r = results[cls];
    const m = art.master(r.rgba, r.fit, Rt);
    r.master = m.img; r.scale = m.scale;
    r.probes = { transparent: r.probes.transparent.map(([x, y]) => m.map(x, y)), opaque: r.probes.opaque.map(([x, y]) => m.map(x, y)) };
    r.metrics = art.measure(m.img);
    r.evidence = art.evidence(m.img, cls);
    r.masterBytes = art.masterBytes(m.img);
    r.runtimeBytes = art.runtimeBytes(m.img);
    delete r.rgba; // the full-resolution extraction is not kept
  }
  return { mapping, sources, results, Rt };
}

function provenance({ mapping, results, Rt }) {
  const out = {
    about: 'GENERATED by tools/icons.js: the provenance of Darren\'s original BANZAI class identities. Do not edit; run node tools/icons.js again.',
    generatedFor: mapping.generatedFor,
    owner: 'Darren (BANZAI UI): original artwork generated for BANZAI with Gemini - not Blizzard art, no Blizzard icon used as a source',
    tool: art.TOOL,
    pipeline: [
      'JPEG decoded in JavaScript (tools/lib/jpeg.js, baseline, centred linear chroma upsampling)',
      'matte removed at full source resolution (tools/lib/matte.js): border-connected matte + flat, neutral, hard-edged matte holes transparent; art near the matte grey kept',
      'seam coverage solved against the local matte and the art behind the edge; the matte grey solved out of every seam pixel',
      'outer ring fitted; ring centre to the canvas centre, every ring the same radius, one uniform scale (Mitchell, linear light, premultiplied alpha)',
      'runtime: 256 x 256 area-filtered, transparent colour bled, 32-bit TGA (tools/lib/identity.js, the build)',
    ],
    master: { size: art.MASTER.size, ringRadius: +Rt.toFixed(2) },
    publication: 'Only the masters / runtime textures are Banzai art to ship; the Gemini source JPEGs stay out of every package. Public packaging remains blocked pending separate release authorization.',
    excluded: mapping.excluded,
    classes: {},
  };
  for (const cls of art.CLASSES) {
    const r = results[cls]; const e = mapping.classes[cls];
    out.classes[cls] = {
      source: { file: e.source, sha256: e.sha256, w: r.img.w, h: r.img.h, format: art.FORMAT },
      extraction: { ...r.summary, ring: { cx: +r.fit.cx.toFixed(2), cy: +r.fit.cy.toFixed(2), R: +r.fit.R.toFixed(2), maxR: +r.fit.maxR.toFixed(2), protrudingRays: r.fit.protruding }, scale: +r.scale.toFixed(5) },
      master: { file: identity.sourceName(cls), sha256: art.sha256(r.masterBytes), ...r.metrics },
      runtime: { file: 'media/BanzaiIdentity/' + cls + '.tga', sha256: art.sha256(r.runtimeBytes), size: identity.CONTRACT.runtime },
      probes: r.probes,
      evidence: r.evidence,
    };
  }
  return out;
}

function sheets({ results }) {
  fs.mkdirSync(path.join(QA, 'sizes'), { recursive: true });
  const masters = art.CLASSES.map((cls) => ({ cls, img: results[cls].master }));
  const runtimes = art.CLASSES.map((cls) => identity.runtimeImage(results[cls].master));
  const write = (name, img) => fs.writeFileSync(path.join(QA, name), png.encode(img.w, img.h, img.px));
  const bg = qa.backgroundSheet(masters);
  write('qa-backgrounds.png', bg.img);
  for (const g of ['magenta', 'white', 'black']) write(`qa-masters-${g}.png`, qa.gridSheet(masters, g).img);
  const seams = qa.seamSheet(masters);
  write('qa-seams.png', seams.img);
  // the difficult edges Darren named, chosen on each master's own art
  const pick = (cls, angleDeg, which) => { const img = results[cls].master; const p = qa.seamPoints(img, (angleDeg * Math.PI) / 180)[which]; return { cls, img, x: p[0], y: p[1] }; };
  const details = [pick('warrior', 300, 2), pick('priest', 90, 1), pick('deathknight', 250, 0), pick('mage', 20, 0), pick('demonhunter', 120, 2), pick('druid', 160, 0)];
  write('qa-edges.png', qa.detailSheet(details).img);
  const sizes = qa.sizeSheet(masters, runtimes);
  write('qa-sizes.png', sizes.img);
  write('qa-sizes-zoom3.png', qa.zoomed(sizes.img, 3));
  for (const { cls, img } of masters) for (const s of [105, 64, 48, 32, 24]) write(path.join('sizes', `${cls}-${s}.png`), resample.resize(img, s));
  fs.writeFileSync(path.join(QA, 'qa-index.json'), JSON.stringify({
    backgrounds: { rows: bg.rows, columns: bg.columns }, seams: { columns: seams.columns, rows: art.CLASSES },
    edges: details.map((d) => d.cls), sizes: { sizes: sizes.sizes, blocks: sizes.blocks, backgrounds: sizes.backgrounds, columns: art.CLASSES },
  }, null, 1));
}

function main() {
  const check = process.argv.includes('--check');
  const t0 = Date.now();
  const d = derive();
  const prov = provenance(d);
  const problems = [];
  for (const cls of art.CLASSES) {
    const r = d.results[cls]; const p = prov.classes[cls];
    if (!r.evidence.pass) problems.push(`${cls}: the colours do not look like the class (${JSON.stringify(r.evidence)}) - check the mapping`);
    if (!r.metrics.corners) problems.push(`${cls}: corners not transparent`);
    const errors = identity.check({ ...r.master, type: 6 });
    if (errors.length) problems.push(`${cls}: ${errors.join('; ')}`);
    for (const [x, y] of p.probes.transparent) if (r.master.px[(y * 1024 + x) * 4 + 3] !== 0) problems.push(`${cls}: matte hole at ${x},${y} not transparent`);
    for (const [x, y] of p.probes.opaque) if (r.master.px[(y * 1024 + x) * 4 + 3] !== 255) problems.push(`${cls}: art at ${x},${y} not opaque`);
  }
  if (check) {
    const file = path.join(ASSETS, 'class-provenance.json');
    const recorded = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
    for (const cls of art.CLASSES) {
      const p = prov.classes[cls];
      const onDisk = path.join(ASSETS, identity.sourceName(cls));
      if (!fs.existsSync(onDisk)) { problems.push(`${cls}: ${identity.sourceName(cls)} missing`); continue; }
      if (art.sha256(fs.readFileSync(onDisk)) !== p.master.sha256) problems.push(`${cls}: ${identity.sourceName(cls)} differs from what the sources give`);
      if (!recorded || JSON.stringify(recorded.classes[cls]) !== JSON.stringify(p)) problems.push(`${cls}: class-provenance.json out of date`);
    }
    console.log(problems.length ? 'icons: ' + problems.length + ' problem(s)\n  ' + problems.join('\n  ') : `icons: 13 masters re-derived from the sources, identical (${Date.now() - t0} ms)`);
    process.exit(problems.length ? 1 : 0);
  }
  if (problems.length) throw new Error('class art:\n  ' + problems.join('\n  '));
  fs.mkdirSync(ASSETS, { recursive: true });
  for (const cls of art.CLASSES) fs.writeFileSync(path.join(ASSETS, identity.sourceName(cls)), d.results[cls].masterBytes);
  fs.writeFileSync(path.join(ASSETS, 'class-provenance.json'), JSON.stringify(prov, null, 1) + '\n');
  sheets(d);
  for (const cls of art.CLASSES) {
    const p = prov.classes[cls]; const x = p.extraction; const m = p.master;
    console.log(`${cls.padEnd(12)} ${p.source.w}x${p.source.h} matte ${x.matte.join(',')} holes ${x.holes} (${x.holePixels} px) near-matte art kept ${x.nearMatteArt} seam ${x.seam.band} px`
      + ` ring R ${x.ring.R} -> ${m.ring.R} (x${x.scale}) centre ${m.ring.cx},${m.ring.cy} margins ${m.margins.top}/${m.margins.right}/${m.margins.bottom}/${m.margins.left} extent ${m.extent.horizontal}x${m.extent.vertical} evidence ${p.evidence.share}/${p.evidence.light}`);
  }
  console.log(`icons: 13 masters (ring radius ${prov.master.ringRadius} of ${art.MASTER.size / 2}) -> assets/identity, QA sheets -> build/icons (${Date.now() - t0} ms)`);
}

if (require.main === module) {
  try { main(); } catch (e) { console.error(String(e.message || e)); process.exit(1); }
}

module.exports = { derive, provenance };
