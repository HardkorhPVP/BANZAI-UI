// draws `str` with blend(x, y, rgb, alpha); h: glyph height in px; anchor 'center' | 'topright';
// colors: one rgb or a function(i, n) giving each glyph's colour (per-letter gradient)
function draw(blend, str, cx, cy, h, colors, anchor = 'center', outline = true) {
  const s = h / 7; const gw = 5 * s; const sp = s;
  const w = str.length * gw + (str.length - 1) * sp;
  let x0 = cx - w / 2; let y0 = cy - h / 2;
  if (anchor === 'topright') { x0 = cx - w; y0 = cy; }
  const colorOf = (i) => (typeof colors === 'function' ? colors(i, str.length) : colors);
  const fill = (dx, dy, fixed, a) => {
    [...str].forEach((ch, i) => {
      const g = GLYPHS[ch]; if (!g) return;
      const c = fixed || colorOf(i);
      for (let gy = 0; gy < 7; gy++) for (let gx = 0; gx < 5; gx++) if (g[gy][gx] === '1') {
        const X = x0 + i * (gw + sp) + gx * s + dx; const Y = y0 + gy * s + dy;
        for (let yy = Math.floor(Y); yy < Math.ceil(Y + s); yy++) for (let xx = Math.floor(X); xx < Math.ceil(X + s); xx++) blend(xx, yy, c, a);
      }
    });
  };
  if (outline) for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) fill(dx, dy, [0, 0, 0], 0.9);
  fill(0, 0, null, 1);
  return { w, h };
}

